import { readFile, writeFile, readdir, mkdir, rm, lstat, realpath } from 'node:fs/promises';
import { resolve, join, dirname, basename, extname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = await realpath(fileURLToPath(new URL('..', import.meta.url)));
const publicRoot = join(projectRoot, 'public');
const distRoot = resolve(projectRoot, 'dist');
const types = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8', '.txt': 'text/plain; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg',
  '.webp': 'image/webp', '.gif': 'image/gif', '.ico': 'image/x-icon',
  '.woff': 'font/woff', '.woff2': 'font/woff2', '.ttf': 'font/ttf', '.pdf': 'application/pdf',
  '.webmanifest': 'application/manifest+json; charset=utf-8'
};

async function collect(directory) {
  const files = [];
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    const filename = join(directory, entry.name);
    if (entry.isSymbolicLink()) throw new Error('Public resources must not contain symbolic links: ' + filename);
    if (entry.isDirectory()) files.push(...await collect(filename));
    else if (entry.isFile()) files.push(filename);
    else throw new Error('Unsupported public resource: ' + filename);
  }
  return files;
}

const files = await collect(publicRoot);
if (!files.includes(join(publicRoot, 'index.html'))) throw new Error('public/index.html is required.');
const assets = Object.create(null);
for (const filename of files) {
  const bytes = await readFile(filename);
  assets['/' + relative(publicRoot, filename).split(sep).join('/')] = {
    type: types[extname(filename).toLowerCase()] || 'application/octet-stream',
    bytes: bytes.byteLength,
    base64: bytes.toString('base64')
  };
}

const [entry, proxy, manifestText] = await Promise.all([
  readFile(join(projectRoot, 'worker/index.js'), 'utf8'),
  readFile(join(projectRoot, 'worker/ai-proxy.js'), 'utf8'),
  readFile(join(projectRoot, '.openai/hosting.json'), 'utf8')
]);
const manifest = JSON.parse(manifestText);
if (manifest.project_id !== 'appgprj_6addcac4e2f08191aab401e40698b1f7') throw new Error('Existing Site identity must be retained.');
if (Object.hasOwn(manifest, 'static')) throw new Error('Remove static hosting configuration for the Worker build.');
if (manifest.d1 !== null || manifest.r2 !== null) throw new Error('This Site does not use D1 or R2 bindings.');
const importLine = "import { handleAI } from './ai-proxy.js';";
const assetMarker = '/* __BEAD_ASSETS__ */ {}';
if (entry.split(importLine).length !== 2 || entry.split(assetMarker).length !== 2) throw new Error('Worker source markers are missing or duplicated.');
const worker = '// Generated by scripts/build.mjs; edit public/ and worker/ sources.\n' + proxy + '\n' + entry.replace(importLine, '').replace(assetMarker, JSON.stringify(assets)) + '\n';

// Resolve and verify the exact output directory before any recursive cleanup.
if (dirname(distRoot) !== projectRoot || basename(distRoot) !== 'dist') throw new Error('Unsafe build output path.');
try {
  const existing = await lstat(distRoot);
  if (!existing.isDirectory() || existing.isSymbolicLink() || await realpath(distRoot) !== distRoot) throw new Error('Build output must be the repository dist directory, not a link.');
} catch (error) { if (error.code !== 'ENOENT') throw error; }
await rm(distRoot, { recursive: true, force: true });
await mkdir(join(distRoot, 'server'), { recursive: true });
await mkdir(join(distRoot, '.openai'), { recursive: true });
await writeFile(join(distRoot, 'server/index.js'), worker);
await writeFile(join(distRoot, '.openai/hosting.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Built self-contained Worker with ${files.length} assets (${Buffer.byteLength(worker)} bytes).`);
